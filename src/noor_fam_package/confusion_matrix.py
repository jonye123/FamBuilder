import numpy as np
import pandas as pd
import networkx as nx
import matplotlib
# Use 'Agg' backend for non-interactive plotting (Essential for HPC/Clusters)
matplotlib.use('Agg') 
import matplotlib.pyplot as plt
from Bio import SeqIO
import os
import argparse
import sys
from scipy.stats import norm

# 1. Setup Arguments
def get_args():
    parser = argparse.ArgumentParser(description="Process Confusion Matrix and Generate Metrics")
    parser.add_argument("--project_name", required=True, help="Project Name (e.g., Fungi, Grass)")
    return parser.parse_args()

def calculate_quartiles_and_filter(group, multiplier=3.5):
    """Filters hits based on score outliers."""
    if len(group) < 2:
        return group
        
    Q1 = group['Score'].quantile(0.25)
    Q3 = group['Score'].quantile(0.75)
    IQR = Q3 - Q1
    lower_bound = Q1 - multiplier * IQR
    
    # We create a copy to avoid SettingWithCopyWarning
    group = group.copy()
    group['Q1'] = Q1
    group['Q3'] = Q3
    group['IQR'] = IQR
    group['LowerBound'] = lower_bound
    
    # Keep only scores above the lower bound
    return group[group['Score'] >= lower_bound]

def main():
    args = get_args()
    project = args.project_name
    
    # 2. Define Generic Paths
    # Matches the structure created by run_all.sh
    base_path = f"{project}HmmDatabase/{project}fam1"
    
    # Input files
    confusion_path = os.path.join(base_path, 'confusionMatrix')
    hog_directory = 'hogDirectoryFiltered' # Assumes we are in the run directory
    hog_stats_path = 'hogMsaStats.tsv'     # Generated by hog_filter.py
    
    # Output files
    filtered_df_path = os.path.join(base_path, 'filtered_confusion_df')
    disagree_path = os.path.join(base_path, 'disagreeMatrix')
    disagree2_path = os.path.join(base_path, 'disagreeMatrix2')
    disagree3_path = os.path.join(base_path, 'disagreeMatrix3') # The "Kill List"
    super_matrix_path = os.path.join(base_path, 'superMatrix')
    gene_info_path = os.path.join(base_path, 'geneInfo')
    plot_dir = "plots"
    
    if not os.path.exists(confusion_path):
        print(f"Error: Confusion Matrix not found at {confusion_path}")
        sys.exit(1)
        
    os.makedirs(plot_dir, exist_ok=True)
    print(f"Processing Confusion Matrix for {project}...")

    # ==========================================
    # PART 1: Filtering & Basic Stats
    # ==========================================
    
    confusion_df = pd.read_csv(confusion_path, delimiter='\t')
    
    # Filter based on IQR scores
    print("Filtering low-scoring outliers...")
    filtered_confusion_df = confusion_df.groupby('HmmHogHit').apply(calculate_quartiles_and_filter).reset_index(drop=True)
    filtered_confusion_df.to_csv(filtered_df_path, sep='\t', index=False)
    
    # Reload for safety/consistency
    confusion_df = pd.read_csv(filtered_df_path, delimiter='\t')

    # ==========================================
    # PART 2: Disagreement Matrices
    # ==========================================
    
    print("Calculating Disagreement Matrix...")
    disagree_df = confusion_df.groupby(['Hog', 'HmmHogHit']).size().reset_index(name='count')
    
    # Filter where HOG != HMM
    disagree_df = disagree_df[disagree_df['Hog'] != disagree_df['HmmHogHit']]
    disagree_df = disagree_df[['count', 'Hog', 'HmmHogHit']]
    disagree_df = disagree_df.rename(columns={'count': 'count','Hog': 'hog','HmmHogHit': 'hmmHogHit'})
    disagree_df.to_csv(disagree_path, sep='\t', index=False)

    # Calculate Ratios
    hog_count = confusion_df['Hog'].value_counts()
    disagree_df['hogSize'] = disagree_df['hog'].map(hog_count)
    disagree_df['ratio'] = disagree_df['count'].values / disagree_df['hogSize']
    disagree_df.rename(columns={'count': 'mismatchCount'}, inplace=True)
    
    columns = ['hog', 'hmmHogHit', 'mismatchCount', 'hogSize', 'ratio']
    disagree_df = disagree_df[columns]
    disagree_df.to_csv(disagree2_path, sep='\t', index=False)

    # Grouping for the Final "Kill List" (DisagreeMatrix3)
    df_d2 = pd.read_csv(disagree2_path, sep='\t')
    grouped = df_d2.groupby(['hog', 'hogSize']).agg({'mismatchCount': 'sum'}).reset_index()
    grouped['new_ratio'] = grouped['mismatchCount'] / grouped['hogSize']
    grouped['hmmWrongCount'] = df_d2.groupby(['hog', 'hogSize']).size().values
    
    grouped = grouped.rename(columns={'new_ratio': 'ratio', 'hog': 'hog'})
    grouped = grouped[['hog', 'hmmWrongCount', 'mismatchCount', 'hogSize', 'ratio']]
    grouped = grouped.sort_values(by='mismatchCount', ascending=False)
    
    # Save the critical file used by main.sh to delete bad HMMs
    grouped.to_csv(disagree3_path, sep='\t', index=False)
    print(f"Identified {len(grouped)} problematic HOGs.")

    # ==========================================
    # PART 3: Gene Info & Super Matrix
    # ==========================================

    print("Generating Gene Info...")
    if os.path.exists(hog_directory):
        with open(gene_info_path, 'w') as f_out:
            f_out.write("hog\tgene\tgene_length\n")
            for filename in os.listdir(hog_directory):
                if filename.endswith(".fasta"):
                    hog_id = filename.split('.')[1] if '.' in filename else filename.replace(".fasta", "")
                    hog_file = os.path.join(hog_directory, filename)
                    try:
                        for record in SeqIO.parse(hog_file, "fasta"):
                            f_out.write(f"{hog_id}\t{record.id}\t{len(record.seq)}\n")
                    except:
                        pass
    else:
        print(f"Warning: {hog_directory} not found. Skipping Gene Info generation.")

    # Load Data for SuperMatrix
    if os.path.exists(gene_info_path) and os.path.exists(hog_stats_path):
        geneInfo = pd.read_csv(gene_info_path, delimiter='\t')
        disagreeMatrix3 = pd.read_csv(disagree3_path, delimiter='\t')
        hogMsaStats = pd.read_csv(hog_stats_path, delimiter='\t')

        merged_df = pd.merge(confusion_df, geneInfo, left_on='Gene', right_on='gene')
        merged_df2 = pd.merge(merged_df, disagreeMatrix3, left_on='Hog', right_on='hog', how='left')
        final_df = pd.merge(merged_df2, hogMsaStats, left_on='Hog', right_on='HOG', how='left')

        # Cleanup columns
        cols_to_drop = ['gene', 'hog_x', 'hog_y', 'HOG', 'listOfLengths', 'min', 'max', 'species_count', 'gene_count']
        final_df.drop([c for c in cols_to_drop if c in final_df.columns], axis=1, inplace=True)
        
        superMatrix = final_df

        # Calculate Z-Scores
        superMatrix['z_scores'] = ((superMatrix['gene_length'] - superMatrix['mean']) / superMatrix['sd']).fillna(0)
        
        superMatrix.to_csv(super_matrix_path, sep='\t', index=False)
        
        # Wrong Matrix (Matches that missed)
        wrongMatrix = superMatrix[superMatrix['Hog'] != superMatrix['HmmHogHit']]
        wrongMatrix.to_csv(os.path.join(base_path, 'wrongMatrix'), sep='\t', index=False)
        
        # ==========================================
        # PART 4: Plotting (Saved to Files)
        # ==========================================
        print(f"Generating plots in {plot_dir}...")
        
        # 1. Histogram of Scores
        plt.figure()
        plt.hist(confusion_df['Score'], bins=50)
        plt.title('Histogram of Scores')
        plt.grid()
        plt.savefig(f"{plot_dir}/hist_scores.png")
        plt.close()

        # 2. Network Graph of Errors
        if not wrongMatrix.empty:
            try:
                G = nx.DiGraph()
                toGraph = wrongMatrix[['Hog', 'HmmHogHit']].drop_duplicates()
                # Limit to top 100 edges to prevent crash on huge datasets
                if len(toGraph) > 100:
                    toGraph = toGraph.head(100)
                
                edges = toGraph.to_records(index=False)
                G.add_edges_from(edges)
                
                plt.figure(figsize=(10, 10))
                pos = nx.spring_layout(G)
                nx.draw(G, pos, with_labels=True, font_size=8, node_size=300)
                plt.title('Directed graph of incorrect HMM assignments (Top 100)')
                plt.savefig(f"{plot_dir}/network_errors.png")
                plt.close()
            except Exception as e:
                print(f"Skipping Network Graph: {e}")

        # 3. Z-Score Distribution
        plt.figure()
        z_scores_filtered = superMatrix['z_scores'].replace([np.inf, -np.inf], 0)
        plt.hist(z_scores_filtered, density=True, bins=100)
        plt.title('Z-Score of gene length')
        plt.grid()
        plt.savefig(f"{plot_dir}/hist_zscores.png")
        plt.close()

        print("Metrics and plots generation complete.")
    else:
        print("Skipping SuperMatrix generation (Missing geneInfo or hogMsaStats).")

if __name__ == "__main__":
    main()