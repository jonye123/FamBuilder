#!/bin/bash

# NoorFam/FamBuilder Iterative HMM Pipeline
# Usage: ./main.sh <input_file> <project_name> <threads>

# 1. Inputs & Defaults
INPUT_FILE=${1}
FASTA_DIR=${2}
PROJECT_NAME=${3:-"myfam"}
THREADS=${4:-4}

# 2. Validation
if [[ ! -f "$INPUT_FILE" ]]; then
    echo "Error: Input file $INPUT_FILE not found."
    exit 1
fi

# Activate environment
eval "$(micromamba shell hook bash)"
micromamba activate orthofinder

# Function: Finalize and Press HMM Database
# This prevents code duplication
finalize_pipeline() {
    local current_dir=$1
    local bp=$2
    
    echo "Finalizing HMM Database..."
    # Remove low-quality HMMs
    while read -r item; do
        rm -f "${current_dir}/${PROJECT_NAME}HmmLib/${item}.hmm"
    done < <(tail -n +2 "${current_dir}/${bp}/disagreeMatrix3" | awk '{print $1}')

    mkdir -p HMMFinal
    cat "${current_dir}/${PROJECT_NAME}HmmLib/"* > "HMMFinal/${PROJECT_NAME}"
    hmmpress -f "HMMFinal/${PROJECT_NAME}"
    
    # Final Accuracy Pass
    cd "$current_dir" || exit
    python ../confusion_matrix.py --project_name "$PROJECT_NAME"
    cd ..
}

# 3. Iteration Loop
iteration=1
prev_error=""

while true; do
    dir="HmmRun${iteration}"
    echo "--- Starting Iteration $iteration: $dir ---"

    mkdir -p "$dir"/bashScripts
    cp bashScripts/* "$dir"/bashScripts
    cp orthofinder_to_fasta.py "$dir"/
    cp "$INPUT_FILE" "$dir"
    
    cd "$dir" || exit 1

    # --- STEP A: Filter HOGs (Using the new .py script) ---
    echo "Running HOG Filter..."
    python ../hog_filter.py --input_orthogroups "$(basename "$INPUT_FILE")" --fasta_dir "$FASTA_DIR" --project_name "$PROJECT_NAME" --iteration "$iteration"
    if [[ $? -ne 0 ]]; then echo "Error in hog_filter.py"; exit 1; fi

    # --- STEP B: Run HMM Pipeline (Bash) ---
    cd bashScripts || exit 1
    bash run_all.sh "$PROJECT_NAME" "$THREADS" &> all.log
    if [[ $? -ne 0 ]]; then echo "Error in run_all.sh"; exit 1; fi
    cd ..

    # --- STEP C: Calculate Confusion Matrix (Using the new .py script) ---
    echo "Calculating metrics..."
    python ../confusion_matrix.py --project_name "$PROJECT_NAME"
    if [[ $? -ne 0 ]]; then echo "Error in confusion_matrix.py"; exit 1; fi

    # --- STEP D: Accuracy Check ---
    base_path="${PROJECT_NAME}HmmDatabase/${PROJECT_NAME}fam1"
    
    # Calculate error metrics using awk on the files generated by confusion_matrix.py
    mishits=$(tail -n +2 "$base_path"/filtered_confusion_df | awk '$2 != $3' | wc -l)
    total_genes=$(tail -n +2 "$base_path"/geneInfo | wc -l)
    hits=$(tail -n +2 "$base_path"/filtered_confusion_df | wc -l)

    percent_error=$(awk -v m="$mishits" -v t="$total_genes" -v h="$hits" 'BEGIN {printf "%.8f", ((m + t - h) / t) * 100}')
    echo "Iteration $iteration Error: $percent_error%"

    # --- STEP E: Termination Logic ---
    if [[ -n "$prev_error" ]]; then
        diff=$(awk -v e1="$percent_error" -v e2="$prev_error" 'BEGIN {print (e1 > e2) ? e1 - e2 : e2 - e1}')
        threshold=0.000001
        
        if (( $(echo "$diff < $threshold" | bc -l) )); then
            echo "Convergence reached. Finalizing..."
            cd ..
            finalize_pipeline "$dir" "$base_path"
            break
        fi
    fi

    if (( iteration >= 15 )); then
        echo "Max iterations reached. Finalizing..."
        cd ..
        finalize_pipeline "$dir" "$base_path"
        break
    fi

    prev_error="$percent_error"
    cd ..
    ((iteration++))
done

echo "FamBuilder finished after $iteration iterations."